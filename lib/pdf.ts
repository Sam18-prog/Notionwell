import { jsPDF } from 'jspdf';
import { Deck } from '@/lib/app';

export function exportDeckToPDF(deck: Deck, subjectName?: string): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  // Header Box / Colors
  doc.setFillColor(37, 99, 235); // Primary Blue #2563EB
  doc.rect(margin, y, contentWidth, 22, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(deck.name, margin + 5, y + 9);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const subText = subjectName ? `Subject: ${subjectName}  •  ${deck.flashcards.length} Flashcards` : `${deck.flashcards.length} Flashcards`;
  doc.text(subText, margin + 5, y + 16);

  y += 28;

  // Flashcards List
  doc.setTextColor(15, 23, 42); // Dark slate #0F172A

  deck.flashcards.forEach((card, index) => {
    // Check if space needed for Question + Answer box (~35mm minimum)
    if (y + 35 > pageHeight - margin) {
      doc.addPage();
      y = margin;
    }

    const cardNum = index + 1;

    // Card Header Bar
    doc.setFillColor(241, 245, 249); // Light slate #F1F5F9
    doc.rect(margin, y, contentWidth, 7, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(37, 99, 235);
    const cardTitle = card.topic ? `CARD #${cardNum} — Topic: ${card.topic}` : `CARD #${cardNum}`;
    doc.text(cardTitle, margin + 3, y + 5);

    y += 10;

    // Question
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(15, 23, 42);
    doc.text(`Q: `, margin + 3, y);

    doc.setFont('helvetica', 'normal');
    const qLines = doc.splitTextToSize(card.question, contentWidth - 12);
    doc.text(qLines, margin + 10, y);
    y += qLines.length * 5 + 3;

    // Answer
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(16, 185, 129); // Emerald Green #10B981
    doc.text(`A: `, margin + 3, y);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(51, 65, 85);
    const aLines = doc.splitTextToSize(card.answer, contentWidth - 12);
    doc.text(aLines, margin + 10, y);
    y += aLines.length * 5 + 6;

    // Divider Line between cards
    doc.setDrawColor(226, 232, 240);
    doc.line(margin, y - 2, margin + contentWidth, y - 2);
    y += 4;
  });

  // Footer on all pages
  const totalPages = (doc.internal as any).getNumberOfPages();
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });

  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184); // #94A3B8
    doc.text(`Generated by Notionwell  •  ${dateStr}`, margin, pageHeight - 8);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 20, pageHeight - 8);
  }

  // File Name Sanitization
  const safeDeckName = deck.name.replace(/[^a-zA-Z0-9]/g, '-').replace(/-+/g, '-');
  const safeSubjectName = (subjectName || 'Notionwell').replace(/[^a-zA-Z0-9]/g, '-').replace(/-+/g, '-');
  const filename = `${safeSubjectName}-${safeDeckName}.pdf`;

  doc.save(filename);
}
